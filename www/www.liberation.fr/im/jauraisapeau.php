					<strong>Ceci est une fiction.</strong><br>					<!--htdig_noindex--><p><i>«C'est le petit Frantz qui l'a trouvée.»</i> La superballe super rebondissante faisait sursauter les passants dans cette ruelle pavée du quartier de l'église Sainte-Elisabeth, à Marburg (Allemagne). Elle est passée par la mince ouverture d'un soupirail et tombée dans la cave d'un immeuble en restauration. <i>«Le petit Frantz a poussé la vitre en passant les pieds par les barreaux. C'est une atroce odeur de chair en décomposition qui est alors remontée. Le petit Frantz s'en souviendra toute sa vie.»</i> Il est comme ça, le lieutenant Gerd Hanke. Il vous raconte des horreurs sur un ton neutre. 42 ans, <i>profiler</i> pour la police criminelle fédérale, formé aux écoles du FBI américain et fameux pour avoir, entre autres, capturé il y a cinq ans le comptable du fisc de Düsseldorf qui se prenait pour la réincarnation de Torquemada (30 contribuables fraudeurs dépecés avoués, 84 soupçonnés), il vous tend les photos à bout de bras. <i>«Vous voulez voir?»</i>, comme si c'étaient celles de ses vacances en famille. Non, merci, on vient d'absorber un petit-déjeuner typique aussi cossu que les maisons à colombages de ses terres luthériennes –et on tient à le garder. Alors, il reprend froidement: <i>«Hilde Gardener, étudiante. 22 ans. Etranglée. Non violée. Vraisemblablement torturée. Le corps portait des centaines de brûlures de toutes tailles. On enquête sur elle.»</i> Il range ses photos sans les regarder. Il en connaît les moindres détails. <i>«Dans la poussière de charbon, il y avait écrit, avec le sang de la victime, Sol Invictus.»</i> Hanke donne cet indice en passant, comme si c'était un détail, et pourtant il est d'importance: c'est le signe qu'on aurait affaire à un serial killer plus cérébral que sexuel... </p>

<p>Petit sourire désabusé: le lieutenant Hanke semble décidément en avoir vu d'autres. D'ailleurs il en a vu d'autres, en novembre encore, à Wittenberg. Dans la cave d'une demeure toute proche du Collegium Augusteum, où enseigna Luther, justement, se trouvait le cadavre de Carl Breitner, un extrémiste, animateur d'un webzine ultra catholique aux velléités européennes. <i>«Le corps était dans un état avancé.»</i> Etranglé également, avec un chapelet en perles de bois d'olivier. Gerd Hanke ne laisse rien au hasard: <i>«Chapelet artisanal. Fabriqué dans une île grecque. Très solide. Bonne qualité.»</i> On n'en doute pas. <i>«La piste politique est écartée. Nous avons passé en revue la vie de Breitner jusqu'à la dernière minute.»</i> Hanke récite ses fiches. <i>«Pas de perversion. D'ordinaire ces catholiques sont attirés par la damnation, mais pas lui... Breitner était juste notre version locale du fou de Dieu.»</i> Alors? Hanke dégaine d'autres photos (non merci). <i>«Il y avait également Sol Invictus de gravé sur la rampe d'escalier, et malgré la décomposition du corps on a remarqué de petites inscriptions ésotériques. C'est pourquoi on m'a appelé.»</i> Petit pincement des lèvres minces: <i>«L'assassin a gravé la formule avec un morceau de la mâchoire supérieure.»</i></p>

<p>Concernant le troisième meurtre découvert avant-hier à Francfort, à deux pas de la Stadt-und Universitätsbibliothek, le lieutenant reconnaît disposer pour l'heure de moins d'indices: la victime est inconnue. Un homme jeune. <i>«Le légiste s'en occupe. J'attends son rapport.»</i> Hanke consulte un banal calepin: <i>«Premier constat. Probablement des brûlures. Des symboles ressemblant à ceux de Marburg et de Wittenberg aux endroits encore identifiables du corps... Et puis Sol Invictus, toujours, gravé sur la porte en bois avec un morceau de la...»</i> On interrompt le lieutenant. Ça ira… On refuse, une fois de plus, sa pile de photographies. Il va falloir qu'on sorte prendre un peu l'air. On se demande si le lieutenant se rend compte qu'il ne faut pas qu'il parle trop boulot avec les gens. Il récapitule, concentré: <i>«C'est probablement toujours le même rituel: des victimes isolées. Etranglement et brûlures. Les symboles ésotériques et cette formule, Sol Invictus. Vous avez des questions?»</i>, enchaîne-t-il, imperturbable. Devant notre trouble, il continue, avec ce petit sourire froid: <i>«Très bien. Je vais recevoir maintenant vos confrères Italiens. Je communique avec la presse car je ne veux pas perdre de temps. J'ai décidé de provoquer au plus vite ce monstre afin qu'il commette une erreur.»</i> Silence, puis: <i>«J'aurai sa peau.»</i></p>

<p>Et soudain, on frémit. On prend peur, tant à la perspective de croiser le serial killer sur son chemin, que parce qu'on réalise que les paupières du lieutenant Gerd Hanke, jamais ne se baissent sur ses yeux bleu pâle.<!--/htdig_noindex-->

