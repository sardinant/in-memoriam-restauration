					<strong>Ceci est une fiction.</strong><br>					<!--htdig_noindex--><p><img src='/img/lettrines/l.gif' align='left'>'angoisse est à son comble au sein de SKL Network, agence de presse pour laquelle travaille le reporter Jack Lorski, mystérieusement disparu avec son assistante depuis février dernier tandis qu'ils étaient sur la trace d'un serial killer particulièrement dangereux (lire <i>Libération</i> du 21 mars 2003). Arnaud Ivan, directeur de SKL Network, a trouvé ce matin dans sa boîte aux lettres un étrange CD-Rom, vraisemblablement créé par le psychopathe soupçonné d'avoir fait disparaître Jack Lorski et Karen Gijman.</p>

<p><i>«J'ignore comment ce CD-Rom est parvenu jusque-là. On enquête en interne. Toutefois, pour ce que nous avons pu en voir -car le disque contient des parties verrouillées par des codes–, il s'agirait d'une sorte de jeu de piste ésotérique. Cela confirme hélas nos soupçons: Jack et Karen sont entre les griffes de celui qu'ils traquaient. Et force est de reconnaître que ce type est particulièrement tordu.»</i></p>

<p>Tordu et novateur puisque de mémoire de profiler, c'est la première fois qu'un serial killer -toujours tenté d'attirer l'attention de la police et de faire «reconnaître» son «travail»- utilise ce mode de revendication. D'ordinaire ce sont des lettres ou des coups de fils, au mieux des cassettes vidéo. <i>«Là, le type a créé une sorte d'œuvre multimédia au graphisme subjuguant et inquiétant, composé d'épreuves à passer. C'est un raffinement dans la cruauté pour nous qui essayons désespérément d'avoir des nouvelles de Jack et Karen... On a affaire, quoi qu'il en soit, à quelqu'un d'exceptionnellement doué.»</i></p>

<p>Pour les services de la police criminelle, l'affaire ne va pas se révéler aisée et on les dit quelque peu désarçonnés. Si d'un côté cette provocation «normale» rassure, en quelque sorte, car elle prouve que la psychologie du serial killer correspond bien aux pathologies «habituelles», elle inquiète en revanche eu égard à la forme particulièrement élaborée du message adressé. Au ministère de l'Intérieur, qui suit discrètement le déroulement de l'enquête, de crainte que cela ne vienne ternir l'image du nouveau logiciel de traque Salvac «vendu» en fanfare cette année par Nicolas Sarkozy, on veut rassurer. <i>«Il y a une escalade tant dans la perversité que dans la complexité, mais nos services résoudront les énigmes.»</i> Un optimisme loin d'être partagé par tous. Chez SKL Network, on estime qu'il faut être presque plus <i>«gamer que flic. Cela fait appel à une autre forme d'intelligence. Les flics, je ne les sens pas sur ce coup-là»</i>, confie une source proche de la direction. </p>

<p>Pressé par le personnel de son agence, le directeur de SKL Network promet de prendre dans les heures qui suivent une décision, qui s'annonce être elle aussi unique dans l'histoire de la criminalité moderne. On murmure <i>«qu'il serait carrément envisagé de mettre à disposition du public des copies du CD-Rom afin qu'il traque lui aussi le serial killer. Il y a sûrement des compétences quelque part. On ne peut plus rien laisser au hasard.»</i> Les gamers, enquêteurs bénévoles, n'auront qu'à guetter la suite de l'affaire -ou peut-être seulement son commencement, sur le site de SKL Network...</p>

<p>Si la cause est plus que juste, et l'urgence des plus criantes, c'est néanmoins une progression inquiétante dans l'amalgame et la confusion entre le citoyen et la police, entre le réel, horrible, et la fiction désincarnée d'un jeu. Longtemps après «Perdu de vue», la télé flic et la télé réalité, voici le public enquêteur sur CD-Rom et l'Internet… Indéniablement, la déréalisation du monde continue sa marche et cela laisserait tout de même perplexe si des vies n'étaient pas en cause. </p>

<p>Pour l'heure, Arnaud Ivan n'infirme ni ne confirme le choix de faire appel ou non au public, même s'il semblerait que l'application de cette tactique soit déjà quasiment décidée. <i>«Tout ça c'est de la glose indécente</i>, tranche-t-il. <i>On réfléchit dans l'urgence. Je m'en fiche si notre méthode fait couler de l'encre aux sociologues en mal de papiers. Ce que je sais c'est que ces considérations, Jack et Karen à cette heure, ils s'en moquent. S'ils peuvent encore même s'en moquer...»</i> A suivre, donc, sur le site de SKL Network.<!--/htdig_noindex-->
