					<strong>Ceci est une fiction.</strong><br>					<!--htdig_noindex--><p><img src='/img/lettrines/s.gif' align='left'>'il existe un paradis des journalistes, et si celui-ci a un bar, on doit y entendre s'esclaffer Lucien Bodard. Quant au patron du mythique Shanghaï Bar sur Nathan Road, à Kowloon (Hongkong), il doit, lui, moins ricaner devant l'ampleur des dégâts: un commando de cinq personnes est venu terroriser les officiels réunis mercredi soir pour la remise du premier Prix Lucien Bodard, une récompense attribuée pour la première fois aux journalistes d'investigation, à l'initiative des membres français du Press Club de Hongkong. </p>

<p>Le lauréat, mercredi, était Jack Lorski, journaliste honoré pour son scoop remarquable ayant permis de démonter l'an dernier le trafic d'organes humains originaire des Balkans et organisé par le député russe Igor Kourievski, toujours en fuite... Le Shanghaï Bar avait été retenu comme lieu symbolique en souvenir du grand reporter de <i>«France Soir»</i> et romancier, disparu en 1998, qui a donc donné son nom au prix. C'est de cet établissement en effet qu'il s'est vanté, dans un de ses romans, d'avoir effectué nombre de ses enquêtes «de terrain» –il a affirmé qu'il disait aux confrères, de retour de reportage, après les avoir arrosés de copieuses tournées pour récupérer des infos : <i>«Je n'y étais pas, mais je le raconterai mieux que toi»</i>. </p>

<p>La cérémonie de mercredi rassemblait une centaine de personnes: tout le gratin des Pen et Press Club, les diplomates de l'Alliance française, divers officiels chinois et quelques rédacteurs en chef de <i>«Time Asia»</i> et <i>«Asia Week»</i>. <i>«Au moment où Jack devait prendre la parole</i>, confie Leung, un barman encore sous le choc, <i>une vitre a volé en éclats. Le cocktail Molotov a heureusement explosé dans un de nos fauteuils de cuir, ce qui a limité l'impact.»</i> Cris, bousculades, panique. Tandis que deux confrères d'Heartland étouffaient le début d'incendie avec des rideaux, un commando de cinq hommes cagoulés a fait irruption en brandissant des barres de fer. L'assistance ayant été rapidement maintenue en respect par le leader, armé d'une Kalachnikov.</p>

<p><i>«C'était un des plus beaux jours de ma carrière, j'ai cru que c'était ma dernière heure»</i>, avoue Jack Lorski qui pourtant en a vu d'autres, notamment en Irak, en Yougoslavie, au Kosovo ou au Rwanda. <i>«Je ne m'explique toujours pas pourquoi ils ne m'ont pas descendu, d'autant que le chef m'a personnellement menacé en russe.»</i> Le commando a pris la fuite sur trois motos quelques minutes après avoir consciencieusement tout saccagé, notamment le long «mahogany bar» célèbre chez les journalistes qui arpentent cette partie de l'Asie. </p>

<p><i>«Tout s'est passé très vite</i>, rapporte Rupert Fleming, un photographe indépendant dont la police a saisi les clichés qu'il a pris discrètement durant l'incident. <i>Ce sont visiblement des pros.»</i> Les dégâts sont considérables. Le Shanghaï Bar est bon pour plusieurs semaines de travaux. La police chinoise a d'ores et déjà effectué une rafle dans le milieu des émigrés russes du district de North Point. En vain, évidemment, mais il s'agit pour les autorités de montrer qu'on traite l'affaire avec sérieux. </p>

<p>L'émotion passée, les confrères baroudeurs osent maintenant en plaisanter. Un correspondant de <i>«The Independant»</i> estime que <i>«c'est une bonne façon pour certains cadres de journaux de se rendre compte de la dangerosité du métier. Finalement, ils devraient le prendre comme un stage!»</i> Jack Lorski quant à lui se demande si le chèque du lauréat de l'an prochain (10 000 dollars tout de même -autant d'euros, bravo Jack) sera dorénavant augmenté de l'équivalent des frais de restauration du bar. <i>«Mais ne l'écrivez pas»</i>, ajoute-t-il... comme s'il était bien placé pour nous apprendre à nous taire.<!--/htdig_noindex-->

